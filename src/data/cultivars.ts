/** Normalised 0–1 scores used by the radar chart. */
export function cultivarScores(c: Cultivar) {
  const avg = (r: [number, number]) => (r[0] + r[1]) / 2;
  return [
    { label: 'Resa', value: (avg(c.yieldIndoor) - 280) / (700 - 280) },
    { label: 'Velocità', value: 1 - (avg(c.floweringDays) - 40) / (85 - 40) },
    { label: 'Anti-muffa', value: c.moldResistance / 5 },
    { label: 'Facilità', value: 1 - (c.difficulty - 1) / 4 },
    { label: 'Compattezza', value: 1 - (avg(c.heightIndoor) - 60) / (160 - 60) },
    { label: 'Freddo', value: c.coldTolerance / 5 },
  ].map((s) => ({ ...s, value: Math.max(0.05, Math.min(1, s.value)) }));
}
